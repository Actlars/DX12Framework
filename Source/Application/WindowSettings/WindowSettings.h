#pragma once

// -------------------------------------------------------------------------------
// WindowSettings struct
//
// 概要 :
//	ウィンドウの位置・大きさ・最大化状態を、起動をまたいで覚えておくためのもの
//
//	毎回同じ大きさで開き直されると、そのたびに並べ直すことになる
//	終了時の状態を書き出しておき、次の起動でそこから始められるようにする
//
//	保存先はJSON
//	エディタが扱う他の設定ファイルと形をそろえ、
//	おかしくなったときに人が開いて直せるようにするため
//
// 責務の分担 :
//	WindowSettings	値の保持と、ファイルの読み書き（このファイル）
//	Application		Win32のウィンドウから値を取り出し、また反映する
//
//	Win32のAPIをここへ持ち込まないのは、
//	「どう保存するか」と「どこから取ってくるか」を分けておくため
// -------------------------------------------------------------------------------
struct WindowSettings
{
	// -------------------------------------------------------------------------------
	// ウィンドウ枠を含む外形（スクリーン座標）
	//
	//	クライアント領域ではなく外形で持つ
	//	復元するときはSetWindowPos系へそのまま渡せる形がいちばん扱いやすく、
	//	枠の太さがOSの設定で変わっても、見た目の位置がずれないため
	// -------------------------------------------------------------------------------
	int32_t	PositionX	= 0;
	int32_t	PositionY	= 0;
	int32_t	Width		= 0;
	int32_t	Height		= 0;

	// 最大化した状態で終了したか
	// このときPosition/Sizeには「元に戻したときの大きさ」が入る
	bool	Maximized	= false;

	// -------------------------------------------------------------------------------
	// @brief	値として使えるか
	//
	//	初回起動や、ファイルが壊れている場合はfalse
	//	そのときは既定の大きさで開く
	// -------------------------------------------------------------------------------
	bool IsValid() const { return Width > 0 && Height > 0; }

	// -------------------------------------------------------------------------------
	// @brief	設定ファイルから読み込む
	//
	//	ファイルが無い場合もエラーにはしない（初回起動では必ず無いため）
	//
	// @param[in]	_path	設定ファイルのパス
	// @return	true : 読み込めて、内容も使える
	// -------------------------------------------------------------------------------
	bool Load(const std::filesystem::path& _path);

	// -------------------------------------------------------------------------------
	// @brief	設定ファイルへ書き出す
	//
	//	親フォルダが無ければ作る
	//
	// @return	true : 書き出せた
	// -------------------------------------------------------------------------------
	bool Save(const std::filesystem::path& _path) const;
};
