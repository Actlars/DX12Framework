#pragma once

namespace RHI
{
	// -------------------------------------------------------------------------------
	// ResourceStateTracker class
	// 
	// 概要 : 
	//	GPUリソースの現在ステートを記録し、必要なバリアを自動生成して蓄積する
	//	FlushBarriersを呼ぶことで、ためたバリアを一括でコマンドリストに発行する
	// -------------------------------------------------------------------------------
	class ResourceStateTracker
	{
	public:

		// -------------------------------------------------------------------------------
		// コンストラクタ
		// -------------------------------------------------------------------------------
		ResourceStateTracker();

		// -------------------------------------------------------------------------------
		// デストラクタ
		// -------------------------------------------------------------------------------
		~ResourceStateTracker();

		// -------------------------------------------------------------------------------
		// @brief	リソースの初期ステートを登録する
		//			リソース生成時（ColorTarget::Init()等）に一回呼ぶ
		// -------------------------------------------------------------------------------
		void RegisterResource(ID3D12Resource* _pResource, D3D12_RESOURCE_STATES _initialState);

		// -------------------------------------------------------------------------------
		// @brief	未登録の場合のみ初期ステートを登録する。登録済みなら何もしない
		// -------------------------------------------------------------------------------
		void RegisterResourceIfNeeded(ID3D12Resource* _pResource, D3D12_RESOURCE_STATES _initialState);

		// -------------------------------------------------------------------------------
		// @brief	リソースを新しいステートへ遷移させる要求を行う
		//			現在ステートと同じ場合はバリアを生成しない
		// -------------------------------------------------------------------------------
		void TransitionResource(
			ID3D12Resource*			_pResource,
			D3D12_RESOURCE_STATES	_newState,
			UINT					_subResource = D3D12_RESOURCE_BARRIER_ALL_SUBRESOURCES);

		// -------------------------------------------------------------------------------
		// @brief	溜めておいたリソースバリアをコマンドリストに一括で発行する
		// -------------------------------------------------------------------------------
		void FlushBarriers(ID3D12GraphicsCommandList* _pCmd);

		// -------------------------------------------------------------------------------
		// @brief	リソース破棄時に呼ぶ。追跡対象から外す
		// -------------------------------------------------------------------------------
		void UnRegisterResource(ID3D12Resource* _pResource);

	private:

		// -------------------------------------------------------------------------------
		// private variables
		// -------------------------------------------------------------------------------

		std::unordered_map<ID3D12Resource*, D3D12_RESOURCE_STATES>	m_ResourceStates;	// 現在状態
		std::vector<D3D12_RESOURCE_BARRIER>							m_PendingBarriers;	// 保留バリア
		std::mutex													m_Mutex;

	};
}