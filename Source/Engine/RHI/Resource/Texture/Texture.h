#pragma once

// -------------------------------------------------------------------------------
// Includes
// -------------------------------------------------------------------------------
#include <Engine/RHI/Resource/DescriptorHeap/DescriptorPool/DescriptorPool.h>

namespace RHI
{
	// -------------------------------------------------------------------------------
	// Texture class
	// 
	// 概要 : 
	//		テクスチャ１枚分のGPUリソースとSRVハンドルを管理するクラス
	//		DescriptorPoolからSRVハンドルを借り受け
	//		デストラクタで自動的に返却する
	// 
	// 使い方 : 
	//		Texture tex;
	//		Tex.Init(_pDevice, _pQueue, _pPool, L"Assets/kerusi-.png");
	//		CmdList->SetGraphicsRootDescriptorTable(1, tex.GetHandleGPU());
	// -------------------------------------------------------------------------------
	class Texture
	{

	public:

		// -------------------------------------------------------------------------------
		//	コンストラクタ
		// -------------------------------------------------------------------------------
		Texture() = default;

		// -------------------------------------------------------------------------------
		//	デストラクタ
		// -------------------------------------------------------------------------------
		~Texture() { Term(); }

		// -------------------------------------------------------------------------------
		// @brief	テクスチャを初期化（ファイルからロードしてGPUへアップロード）
		//
		// @param[in]	_pDevice	D3D12コマンド
		// @param[in]	_pQueue		コピー用コマンドキュー
		// @param[in]	_pPool		SRVを割り当てるDescriptorPool
		// @param[in]	_path		テクスチャファイルのパス
		// @retval	true	初期化成功
		// @retval	false	初期化失敗
		// -------------------------------------------------------------------------------
		bool Init(
			ID3D12Device*		_pDevice,
			ID3D12CommandQueue* _pQueue,
			DescriptorPool*		_pPool,
			const std::wstring& _path);

		// -------------------------------------------------------------------------------
		// @brief	既存のGPUリソースからSRVを生成する
		//			ダミーテクスチャやRenderTargetをSRVとしてバインドする場合に使用
		// 
		// @param[in]	_pDevice	デバイス
		// @param[in]	_pPool		SRVを割り当てるDescriptorPool
		// @param[in]	_pResource	既存のGPUリソース（所有権なし）
		// @param[in]	_format		SRVのフォーマット
		// @param[in]	_isCube		キューブマップかどうか
		// @retval	true	成功
		// @retval	false	失敗
		// -------------------------------------------------------------------------------
		bool InitFromResource(
			ID3D12Device*	_pDevice,
			DescriptorPool* _pPool,
			ID3D12Resource* _pResource,
			DXGI_FORMAT		_format = DXGI_FORMAT_R8G8B8A8_UNORM,
			bool			_isCube = false);

		// -------------------------------------------------------------------------------
		// @brief	SRV + UAV両対応のテクスチャを新規作成する
		//			コンピュートシェーダーで書き込み、
		//			その後マテリアルで読み取りする「ベイク先の格納先」用途の想定
		// 
		// @param[in]	_pDevice	デバイス
		// @param[in]	_pPool		SRV/UAVを割り当てるDescriptorPool
		// @param[in]	_width		テクスチャ横幅
		// @param[in]	_height		テクスチャ縦幅
		// @param[in]	_format		ピクセルフォーマット(UAV対応フォーマットである必要がある)
		// @retval	true	成功
		// @retval	false	失敗
		// ※注意 : 生成直後のリソース状態は、D3D12_RESOURCE_STATE_	UNORDERED_ACCESS
		//			コンピュートシェーダーでの書き込み後、SRVとして読む前に
		//			呼び出し側でPIXEL_SHADER_RESOURCE等へバリアを張る
		// -------------------------------------------------------------------------------
		bool InitAsUAVTarget(
			ID3D12Device*	_pDevice,
			DescriptorPool* _pPool,
			uint32_t		_width,
			uint32_t		_height,
			DXGI_FORMAT		_format);

		// -------------------------------------------------------------------------------
		// @brief	終了処理。GPUリソースとSRVハンドルを開放する
		// -------------------------------------------------------------------------------
		void Term();

		// -------------------------------------------------------------------------------
		// @brief	シェーダーにバインドするためのGPUハンドルを返す
		// -------------------------------------------------------------------------------
		D3D12_GPU_DESCRIPTOR_HANDLE GetHandleGPU() const;

		// -------------------------------------------------------------------------------
		// @brief	CPUからSRVを書き込むためのCPUハンドルを返す
		// -------------------------------------------------------------------------------
		D3D12_CPU_DESCRIPTOR_HANDLE GetHandleCPU() const;

		// -------------------------------------------------------------------------------
		// @brief	UAV用のCPU/GPUハンドルを返す
		// -------------------------------------------------------------------------------
		D3D12_GPU_DESCRIPTOR_HANDLE GetHandleGPU_UAV() const;
		D3D12_CPU_DESCRIPTOR_HANDLE GetHandleCPU_UAV() const;

		// -------------------------------------------------------------------------------
		// @brief	テクスチャの横幅を返す
		// -------------------------------------------------------------------------------
		uint32_t GetWidth() const;

		// -------------------------------------------------------------------------------
		// @brief	テクスチャの縦幅を返す
		// -------------------------------------------------------------------------------
		uint32_t GetHeight() const;

		// -------------------------------------------------------------------------------
		// @brief	テクスチャのピクセルフォーマットを返す
		// -------------------------------------------------------------------------------
		DXGI_FORMAT GetFormat()const;

		// -------------------------------------------------------------------------------
		// @brief	GPUリソースを返す。（RenderTargetへのバインド等へ使用）
		// -------------------------------------------------------------------------------
		ID3D12Resource* GetResource()const;

		// -------------------------------------------------------------------------------
		// @brief	Bindless用 : ディスクリプタヒープ内でのインデックスを返す
		// -------------------------------------------------------------------------------
		uint32_t GetIndex() const;

		// -------------------------------------------------------------------------------
		// @brief	ハンドルの有無を返す
		// -------------------------------------------------------------------------------
		bool IsValid()const;

		// -------------------------------------------------------------------------------
		// @brief	Bindless用 : UAVのディスクリプタヒープ内でのインデックスを返す
		// -------------------------------------------------------------------------------
		uint32_t GetIndexUAV()const;

		// -------------------------------------------------------------------------------
		// @brief	UAVハンドルを保持しているか（InitAsUAVTargetで作成されたか）を返す
		// -------------------------------------------------------------------------------
		bool HasUAV()const;

	private:

		// -------------------------------------------------------------------------------
		// @brief	ファイルパスの拡張子からDDSかどうか判定する
		// -------------------------------------------------------------------------------
		static bool IsDDS(const std::wstring& _path);

		// -------------------------------------------------------------------------------
		// @brief	CPUメモリ上の画像データをGPU（DEFAULTヒープ）へアップロードする
		// 
		// フロー
		// 1. DEFAULTヒープにGPUリソースを作成（コピー先）
		// 2. UPLOADヒープに中間バッファを作成
		// 3. ロード専用CommandListでUpdateSubresourcesを実行
		// 4. リソースバリアをCOPY_DEST → PIXEL_SHADER_RESOURCEに遷移
		// 5. フェンスで同期し、中間バッファの早期解放を防ぐ
		// 
		// @param[in]	_image	DirectXTexのScratchImage（CPUメモリ上のデータ）
		// @param[in]	_meta	テクスチャのメタ情報（サイズ、フォーマット等）
		// @param[out]	_outResource	アップロード先のGPUリソース
		// @retval	true	成功
		// @retval	false	失敗
		// -------------------------------------------------------------------------------
		bool UploadToGPU(
			const DirectX::ScratchImage&	_image,
			const DirectX::TexMetadata&		_meta,
			ComPtr<ID3D12Resource>&			_outResource);

		// -------------------------------------------------------------------------------
		// @brief	GPUリソースに対してSRVをDescriptorPoolに登録する
		// 
		// テクスチャの種類（通常2D / 配列 / キューブマップ）を自動判別してSRVを作成
		// 
		// @param[in]	_meta	テクスチャのメタ情報
		// -------------------------------------------------------------------------------
		void CreateSRV(const DirectX::TexMetadata& _meta);

		// -------------------------------------------------------------------------------
		// @brief	GPUリソースに対してSRVをDescriptorPoolに登録する（リソース直接指定）
		// -------------------------------------------------------------------------------
		void CreateSRVFromResource(
			ID3D12Resource* _pResource,
			DXGI_FORMAT		_format,
			bool			_isCube);

		// -------------------------------------------------------------------------------
		// @brief	GPUリソースに対して、UAVをDescriptorPoolに登録する
		// -------------------------------------------------------------------------------
		void CreateUAVFromResource(
			ID3D12Resource* _pResource,
			DXGI_FORMAT		_format);

		// -------------------------------------------------------------------------------
		// private variables
		// -------------------------------------------------------------------------------
		ID3D12Device*		m_pDevice		= nullptr;	// D3D12デバイス（所有権なし）
		ID3D12CommandQueue* m_pQueue		= nullptr;	// コマンドキュー（所有権なし）
		DescriptorPool*		m_pPool			= nullptr;	// SRVプール（所有権なし）
		DescriptorHandle*	m_pHandle		= nullptr;	// プールから借りたSRVハンドル
		DescriptorHandle*	m_pUAVHandle	= nullptr;	// UAV専用ハンドル

		ComPtr<ID3D12Resource>	m_pResource;		// GPUリソース本体

		uint32_t	m_Width		= 0;					// テクスチャ横幅
		uint32_t	m_Height	= 0;					// テクスチャ縦幅
		DXGI_FORMAT m_Format	= DXGI_FORMAT_UNKNOWN;	// ピクセルフォーマット

		// コピー禁止
		Texture(const Texture&) = delete;
		void operator = (const Texture&) = delete;

	};
}
