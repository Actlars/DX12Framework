#pragma once

// -------------------------------------------------------------------------------
// AssetTextFile
//
// 概要 :
//	テキスト形式のアセット（.prefab / .scene など）を読み書きする、共通の入り口
//
//	どのアセットも「ファイル全体を文字列として読む / 書く」だけで、
//	中身の解釈はそれぞれのアセットが行う
//	同じ処理を各所に書くと、失敗時の扱いや改行の扱いが少しずつ食い違うため、
//	1か所へまとめている
//
//	例外は投げない
//	壊れたファイルや存在しないパスでエディタが落ちないよう、
//	失敗はすべて戻り値で返す
// -------------------------------------------------------------------------------
namespace AssetTextFile
{
	// -------------------------------------------------------------------------------
	// @brief	ファイル全体を文字列として読む
	//
	// @return	true : 読めた / false : 開けなかった
	// -------------------------------------------------------------------------------
	bool Read(const std::filesystem::path& _path, std::string& _outText);

	// -------------------------------------------------------------------------------
	// @brief	文字列をファイルへ書き出す（既存の内容は捨てる）
	//
	//	親フォルダが無い場合は作る
	//
	// @return	true : 書けた
	// -------------------------------------------------------------------------------
	bool Write(const std::filesystem::path& _path, std::string_view _text);

	// -------------------------------------------------------------------------------
	// @brief	拡張子が一致するかを、大文字小文字を無視して調べる
	//
	// @param[in]	_extension	"." を含む拡張子（".prefab" など）
	// -------------------------------------------------------------------------------
	bool HasExtension(const std::filesystem::path& _path, std::string_view _extension);
}
