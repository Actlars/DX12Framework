#pragma once
// -------------------------------------------------------------------------------
// Includes
// -------------------------------------------------------------------------------
class GameObject;
class GameObjectManager;

// -------------------------------------------------------------------------------
// PrefabComponentData struct
//
// 概要 :
//	プレファブに記録された、コンポーネント1つぶんの情報
//
//	型そのものではなく「型の名前」と「値」で持つ
//	ファイルはC++の型を知らないため名前で引き当てるしかないのと、
//	知らない型が入っていても読み飛ばせるようにするため
// -------------------------------------------------------------------------------
struct PrefabComponentData
{
	std::string		TypeName;	// ComponentRegistryの内部名（"TransformComponent"など）
	nlohmann::json	Values;		// その型ごとの値
};

// -------------------------------------------------------------------------------
// PrefabAsset struct
//
// 概要 :
//	「オブジェクト1体分の設計図」
//
//	シーンに置かれた実体ではなく、そこから写し取った値だけを持つ
//	同じ設計図から何体でも作れ、ファイルとして保存して使い回せる
//
//	GameObjectそのものを保存しない理由 :
//		GameObjectはGPUリソースへのポインタなど、実行中にしか意味を持たない
//		ものを抱えている。値だけを抜き出しておくことで、
//		起動をまたいでも、別のシーンでも同じように復元できる
//
//	置き場所について :
//		エディタが無い状態でもプレファブを配置できる必要があるため、
//		データと読み書きはエンジン側に置く
//		コンテンツフォルダへの保存や、取り消せる操作としての配置は
//		エディタ側(Editor::PrefabSystem)が受け持つ
// -------------------------------------------------------------------------------
struct PrefabAsset
{
	std::string	Name	= "New Prefab";	// 配置したときのオブジェクト名の元になる
	bool		Active	= true;

	// 記録順に並ぶ。復元もこの順で行う
	std::vector<PrefabComponentData> Components;
};

// -------------------------------------------------------------------------------
// プレファブの読み書きと、GameObjectとの相互変換
// -------------------------------------------------------------------------------
namespace PrefabIO
{
	// プレファブファイルの拡張子。判定と保存の両方でここを参照する
	constexpr std::string_view kExtension = ".prefab";

	// -------------------------------------------------------------------------------
	// @brief	プレファブをテキスト(JSON)へ書き出す
	//
	//	人が読める形にしておくことで、差分が追え、手で直すこともできる
	// -------------------------------------------------------------------------------
	std::string Serialize(const PrefabAsset& _prefab);

	// -------------------------------------------------------------------------------
	// @brief	テキスト(JSON)からプレファブを読み込む
	//
	//	見つかったキーだけを反映する方針にしているため、
	//	項目が増えても古いファイルはそのまま開ける
	//
	// @return	true : 読み込めた / false : JSONとして壊れている
	// -------------------------------------------------------------------------------
	bool Deserialize(std::string_view _json, PrefabAsset& _outPrefab);

	// ファイルとの読み書き
	bool SaveToFile(const std::filesystem::path& _path, const PrefabAsset& _prefab);
	bool LoadFromFile(const std::filesystem::path& _path, PrefabAsset& _outPrefab);

	// -------------------------------------------------------------------------------
	// @brief	シーン上のオブジェクトから設計図を作る
	// -------------------------------------------------------------------------------
	PrefabAsset CaptureFromObject(const GameObject& _object);

	// -------------------------------------------------------------------------------
	// @brief	設計図からオブジェクトを組み立てる（シーンにはまだ入れない）
	//
	//	知らない型のコンポーネントは読み飛ばす
	//	古いプレファブや、まだ登録していない型が入っていても開けるようにするため
	//
	// @param[in]	_objects	名前の重複を調べる相手のシーン
	// @param[in]	_prefab		もとにする設計図
	// @return	組み立てたオブジェクト（所有権つき）
	// -------------------------------------------------------------------------------
	std::unique_ptr<GameObject> Build(
		const GameObjectManager&	_objects,
		const PrefabAsset&			_prefab);

	// @brief	そのパスがプレファブファイルかどうか
	bool IsPrefabPath(const std::filesystem::path& _path);
}
