#pragma once
// -------------------------------------------------------------------------------
// Includes
// -------------------------------------------------------------------------------
#include <Engine/EditorUI/Docking/DockNode.h>
#include <Engine/EditorUI/Core/Id.h>

namespace EditorUI
{
	// -------------------------------------------------------------------------------
	// DockSpace class
	// 
	// 概要 : 
	//	画面上の１つのドッキング可能な領域全体を管理するクラス。
	//	DockNodeの木を保持し、毎フレームUpdateLayoutで各ノードのBoundsを再計算する
	//	ウィンドウ本体の状態は持たず、どのウィンドウがどのLeafに所属しているかという配置情報だけを持つ
	// -------------------------------------------------------------------------------
	class DockSpace
	{
	public:

		// -------------------------------------------------------------------------------
		// @brief	ルート領域を１つのLeafとして初期化する
		// -------------------------------------------------------------------------------
		void Init(const Rect2D& _rootBounds);

		// -------------------------------------------------------------------------------
		// @brief	ルート領域のサイズが変わった場合に、全ノードのBoundsを再計算する
		// -------------------------------------------------------------------------------
		void UpdateLayout(const Rect2D& _rootBounds);

		// -------------------------------------------------------------------------------
		// @brief	指定したLeafを分割し、新しいウィンドウ用のLeafを作る
		// 
		//	分割元のLeafが持っていたウィンドウはそのまま元の位置（ChildA側）に残り、
		//	新規Leaf（ChildB側）が空の状態で返される。呼び出し側はこのIdに対して
		//	DockWindowIntoLeafを呼んで実際のウィンドウを登録させる
		// 
		//	@param[in]	_leafId		分割するLeafのノードId
		//	@param[in]	_dir		分割方向
		//	@param[in]	_ratio		分割比率
		//	@return		新規作成された空のLeafノードのId。失敗時は-1
		// -------------------------------------------------------------------------------
		int SplitLeaf(int _leafId, DockSplitDir _dir, float _ratio = 0.3f);

		// -------------------------------------------------------------------------------
		// @brief	画面全体(ルート領域)を分割し、外周に新しいLeafを作る
		//
		//	ウィンドウを画面の外までドラッグしたときの受け皿
		//	SplitLeafが「マウス直下のLeafを割る」のに対し、こちらは常に画面全体を割るため
		//	どのレイアウトであっても、指定した辺にウィンドウが吸着する
		//
		//	@param[in]	_dir	吸着させる辺
		//	@param[in]	_ratio	外周側が占める割合
		//	@return		ウィンドウを入れるべきLeafのId。失敗時は-1
		// -------------------------------------------------------------------------------
		int SplitRoot(DockSplitDir _dir, float _ratio = 0.25f);

		// -------------------------------------------------------------------------------
		// @brief	ルート領域の矩形を返す。画面外判定の基準に使う
		// -------------------------------------------------------------------------------
		Rect2D GetRootBounds() const;

		// -------------------------------------------------------------------------------
		// @brief	指定したLeafの末尾にウィンドウをタブとして追加する
		// -------------------------------------------------------------------------------
		void DockWindowIntoLeaf(int _leafId, Id _windowId);

		// -------------------------------------------------------------------------------
		// @brief	ウィンドウをどこかのLeafから削除する
		//			結果としてLeafが空になった場合は、その領域の親のSplitごと
		//			もう一方の兄弟ノードに明け渡される形で木から消える
		// -------------------------------------------------------------------------------
		void UndockWindow(Id _windowId);

		// -------------------------------------------------------------------------------
		// @brief	指定座標を含むLeafノードを探す
		// 
		// @return	見つかったLeafノードのId。見つからなければ-1		
		// -------------------------------------------------------------------------------
		int FindLeafAt(const DirectX::XMFLOAT2& _point) const;

		// -------------------------------------------------------------------------------
		// @brief	指定したウィンドウが所属しているLeafを探す
		// 
		// @return	見つかったLeafノードのId。ドッキングされていなければ-1
		// -------------------------------------------------------------------------------
		int FindLeafOwning(Id _windowId)const;

		// -------------------------------------------------------------------------------
		// @brief	指定Leafが実際にウィンドウを1つ以上収めているかを返す
		//			空のLeafにはウィンドウを吸着させたくない場面で使う
		// -------------------------------------------------------------------------------
		bool IsLeafOccupied(int _leafId) const;

		// -------------------------------------------------------------------------------
		// @brief	指定したLeafのアクティブタブを切り替える
		// -------------------------------------------------------------------------------
		void SetActiveTab(int _leafId, int _tabIndex);

		// -------------------------------------------------------------------------------
		// @brief	指定座標がどこかのSplit境界線に十分近いかを調べる
		// -------------------------------------------------------------------------------
		int FindSplitAt(const DirectX::XMFLOAT2& _point, float _hitThickness) const;

		// -------------------------------------------------------------------------------
		// @brief	指定Splitノード境界線を、_pointの位置に合わせてドラッグ更新する	
		// -------------------------------------------------------------------------------
		bool DragSplit(int _splitId, const DirectX::XMFLOAT2& _point, float _minRatio = 0.05f, float _maxRatio = 0.95f);

		const DockNode* GetNode(int _nodeId) const;
		int GetRootId() const { return m_RootId; }
		bool IsSingleEmptyRoot() const;	// ルート1つだけで空の状態

	private:

		void RecomputeBounds(int _nodeId, const Rect2D& _bounds);
		void MergeUpIfEmpty(int _leafId);	// 空になったLeafを木から取り除く再起関数
		int FindSplitAtRecursive(int _nodeId, const DirectX::XMFLOAT2& _point, float _hitThickness) const;

		std::unordered_map<int, DockNode> m_Nodes;
		int m_NextNodeId	= 0;
		int m_RootId		= -1;

	};
}