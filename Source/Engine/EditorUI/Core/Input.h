#pragma once

namespace EditorUI
{
	enum class MouseButton
	{
		Mouse_Left		= 0,
		Mouse_Right		= 1,
		Mouse_Middle	= 2,
		Mouse_Max		= 3,
	};

	// -------------------------------------------------------------------------------
	// Key : enum
	//
	// 概要 :
	//	EditorUIが実際に使うキーだけを並べた、プラットフォーム非依存のキー識別子
	//	Win32のVK_コードをそのまま持たないのは、EditorUI層をWindows APIから切り離し
	//	将来の他プラットフォーム対応や、テスト時の入力差し替えを容易にするため
	//	VK_コードとの対応付けはApplication(プラットフォーム層)の責務とする
	// -------------------------------------------------------------------------------
	enum class Key : uint8_t
	{
		Backspace,
		Delete,
		Left,
		Right,
		Up,
		Down,
		Home,
		End,
		Enter,
		Escape,
		Tab,

		Ctrl,		// 左右を区別せず、どちらかが押されていればDown扱い
		Shift,
		Alt,

		// -------------------------------------------------------------------------------
		// ショートカットに使う文字キー
		//
		//	アルファベット全部は持たない
		//	「今どのショートカットが存在するか」がこの並びだけで分かるようにするため、
		//	使うキーだけを必要になった時点で足していく
		// -------------------------------------------------------------------------------
		A,			// Ctrl+Aでの全選択に使う
		D,			// Ctrl+Dで複製
		Y,			// Ctrl+Yでやり直し
		Z,			// Ctrl+Zで元に戻す

		F2,			// 名前の変更

		Count		// 要素数。配列サイズの定義にのみ使い、キーとしては使わない
	};

	// Keyを配列の添字として使うためのヘルパー
	// 呼び出し側にstatic_castを書かせないことで、可読性と型の取り違えを防ぐ
	constexpr std::size_t ToIndex(Key _key) { return static_cast<std::size_t>(_key); }
	constexpr std::size_t kKeyCount = ToIndex(Key::Count);

	constexpr std::size_t ToIndex(MouseButton _button) { return static_cast<std::size_t>(_button); }
	constexpr std::size_t kMouseButtonCount = ToIndex(MouseButton::Mouse_Max);

	// -------------------------------------------------------------------------------
	// InputState struct
	//
	// 概要 :
	//	プラットフォーム非依存の入力スナップショット
	//	Contextは「今フレームの状態」と「前フレームの状態」の2つを保持し、その差分から
	//	押した瞬間 / 離した瞬間を求める。そのためこの構造体自身は
	//	エッジ（瞬間）の情報を持たず、常にそのフレームの生の状態だけを持つ
	// -------------------------------------------------------------------------------
	struct InputState
	{
		// スクリーン座標でのマウスの位置。ウィンドウ外や無効値のときは(-1,-1)を初期値にしている
		DirectX::XMFLOAT2	MousePos{ -1.0f,-1.0f };

		// 現在の押下状態のみを持つ。0:左, 1:右, 2:中
		bool				MouseDown[kMouseButtonCount] = { false,false,false };

		// ホイールの回転量（１フレーム当たりの増分）
		float				MouseWheel		= 0.0f;

		// -------------------------------------------------------------------------------
		// 前フレームからの経過時間(秒)
		//
		// EditorUI自身は時刻を計れないため、プラットフォーム層から毎フレーム受け取る
		// ダブルクリックの判定や、エフェクトプレビューの再生に使う
		// -------------------------------------------------------------------------------
		float				DeltaTime		= 0.0f;

		// 現在の押下状態。修飾キー(Ctrl / Shift)の判定に使う。添字はToIndex(Key)
		bool				KeyDown[kKeyCount] = {};

		// -------------------------------------------------------------------------------
		// このフレームに「押された」通知が届いたか
		//
		// KeyDownの前フレームとの差分ではなくOSからの通知をそのまま持つのは、
		// キーの長押しによるオートリピートを取りこぼさないため
		// BackSpaceの押しっぱなしで文字が連続削除される挙動はこれに依存する
		// -------------------------------------------------------------------------------
		bool				KeyPressed[kKeyCount] = {};

		// -------------------------------------------------------------------------------
		// このフレームに確定した入力文字（WM_CHAR相当）
		//
		// KeyDownと分けているのは、実際に入力される文字がIMEやキーボードレイアウト、
		// Shiftの有無によって決まり、キーコードだけからは決定できないため
		// テキスト入力ウィジェットはKeyDownではなくこちらを読む
		// -------------------------------------------------------------------------------
		std::wstring		InputCharacters;

		bool IsKeyDown(Key _key)	const { return KeyDown[ToIndex(_key)]; }
		bool IsKeyPressed(Key _key)	const { return KeyPressed[ToIndex(_key)]; }
	};
}
