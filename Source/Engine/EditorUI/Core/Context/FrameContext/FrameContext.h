#pragma once
// -------------------------------------------------------------------------------
// Includes
// -------------------------------------------------------------------------------
#include <Engine/EditorUI/Core/Id.h>
#include <Engine/EditorUI/Core/Window/WindowFrame.h>
#include <Engine/EditorUI/Core/Context/FrameContext/FrameOutput.h>

namespace EditorUI
{
	// -------------------------------------------------------------------------------
	// FrameContext class
	// 
	// 概要 : 
	//	１フレーム限定のWindowFrameや最終描画出力を所有する
	// -------------------------------------------------------------------------------
	class FrameContext
	{
	public:

		// -------------------------------------------------------------------------------
		// @brief	フレーム開始時の初期化処理
		// -------------------------------------------------------------------------------
		void NewFrame();

		// -------------------------------------------------------------------------------
		// @brief	一時Windowを生成し、描画リストとWindowStackに積む
		// -------------------------------------------------------------------------------
		WindowFrame& PushWindowFrame(WindowState& _state, WindowFlags& _flags);
		// -------------------------------------------------------------------------------
		// @breif	WindowStackの末尾の要素を削除する
		// -------------------------------------------------------------------------------
		void PopWindowFrame();

		// -------------------------------------------------------------------------------
		// @brief	WindowStackを返す
		// -------------------------------------------------------------------------------
		WindowFrame* GetCurrentWindow();
		const WindowFrame* GetCurrentWindow() const;

		// -------------------------------------------------------------------------------
		// @brief	指定したIdのWindowを見つけて返す
		// -------------------------------------------------------------------------------
		WindowFrame* FindWindowFrame(Id _windowId);
		const WindowFrame* FindWindowFrame(Id _windowId) const;

		// -------------------------------------------------------------------------------
		// @brief	描画リストに一時Windowを積む
		// -------------------------------------------------------------------------------
		void AppendDrawList(Id _windowId);

		// -------------------------------------------------------------------------------
		// @brief	すべてのWindowより手前に描くための、フレーム共有の描画リスト
		//
		//	ドッキングのプレビューのように「特定のWindowの外側にも描きたい」ものは
		//	Window自身のDrawListに積むとWindow矩形でクリップされて見えなくなる
		//	そのため、どのWindowにも属さないこのリストを別に用意する
		// -------------------------------------------------------------------------------
		DrawList& GetOverlayDrawList();

		// -------------------------------------------------------------------------------
		// @brief	オーバーレイを最前面として出力に積む。EndFrameの最後に1回だけ呼ぶ
		// -------------------------------------------------------------------------------
		void AppendOverlayDrawList();

		const FrameOutput& GetOutput() const;

	private:

		std::vector<std::unique_ptr<WindowFrame>>	m_Frames;
		std::unordered_map<Id, WindowFrame*>		m_FrameByWindow;
		std::vector<WindowFrame*>					m_WindowStack;
		DrawList									m_Overlay;		// 最前面に描くフレーム共有の描画リスト
		FrameOutput									m_Output;

	};
}
