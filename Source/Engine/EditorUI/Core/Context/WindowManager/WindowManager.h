#pragma once
// -------------------------------------------------------------------------------
// Includes
// -------------------------------------------------------------------------------
#include <Engine/EditorUI/Core/Id.h>
#include <Engine/EditorUI/Core/Window.h>

namespace EditorUI
{
	// -------------------------------------------------------------------------------
	// WindowManager class
	// 
	// 概要 : Windowそのものの永続状態と順序を管理する
	// -------------------------------------------------------------------------------
	class WindowManager
	{
	public:

		// -------------------------------------------------------------------------------
		// @brief	フレームの開始時に行う処理
		// -------------------------------------------------------------------------------
		void BeginFrame();

		// -------------------------------------------------------------------------------
		// @brief	永続Windowの中からIdを持っているものの有無を返す
		// -------------------------------------------------------------------------------
		bool Contains(Id _id) const;

		// -------------------------------------------------------------------------------
		// @brief	指定したIdに対応するWindowStateの生成Or取得を行う
		// 
		// @param[in]	_id		Window固有のId
		// -------------------------------------------------------------------------------
		WindowState& GetOrCreate(Id _id);

		// -------------------------------------------------------------------------------
		// @brief	指定したIdのWindowがあれば返す
		// 
		// @param[in]	_id		Window固有のId
		// @return	Idに応じたウィンドウ。なければnullptr
		// -------------------------------------------------------------------------------
		WindowState* Find(Id _id);
		const WindowState* Find(Id _id) const;

		// -------------------------------------------------------------------------------
		// @brief	指定したIdのWindowの有効化
		// 
		// @param[in]	_id		Window固有のId
		// -------------------------------------------------------------------------------
		void MarkActive(Id _id);

		// -------------------------------------------------------------------------------
		// @brief	Windowの有効化済みかどうかを返す
		// -------------------------------------------------------------------------------
		bool IsActive(Id _id) const;

		// -------------------------------------------------------------------------------
		// @brief	Windowを安全に削除予約する
		// 
		// @param[in]	_id		Window固有のId
		// -------------------------------------------------------------------------------
		void RequestDestroy(Id _id);
		// -------------------------------------------------------------------------------
		// @brief	実際にウィンドウを削除する
		// -------------------------------------------------------------------------------
		std::vector<Id> ConsumePendingDestroy();
		// -------------------------------------------------------------------------------
		// @brief	ウィンドウをすぐに破棄する
		// -------------------------------------------------------------------------------
		void DestroyWindowImmediate(Id _id);

		// -------------------------------------------------------------------------------
		// @brief	指定したWindowのIdをz-order配列の末尾に移動する
		// -------------------------------------------------------------------------------
		void BringToFron(Id _id);

		void SetFocused(Id _id);
		Id GetFocused() const;

		void SetHovered(Id _id);
		Id GetHovered() const;

		const std::vector<Id>& GetWindowOrder() const;

	private:

		std::unordered_map<Id, WindowState> m_States;
		std::vector<Id> m_Order;			// 背面→前面
		std::vector<Id> m_PendingDestroy;

		Id m_FocusedWindow = 0;
		Id m_HoveredWindow = 0;

	};
}
