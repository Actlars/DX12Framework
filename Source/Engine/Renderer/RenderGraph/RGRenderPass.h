#pragma once
// -------------------------------------------------------------------------------
// Includes
// -------------------------------------------------------------------------------
#include "RGPassBuilder.h"

namespace RG
{
	// -------------------------------------------------------------------------------
	// 前方宣言
	// -------------------------------------------------------------------------------
	class ResourceRegistry;

	// -------------------------------------------------------------------------------
	// RenderPass
	// 
	// 概要 : 
	//	1つの描画パス。Setup（リソース宣言）とExecute（実際の描画）を分離して持つ
	// -------------------------------------------------------------------------------
	struct RenderPass
	{
		std::string Name;

		// リソース使用を宣言するフェーズ
		std::function<void(PassBuilder&)> Setup;

		// 実際の描画コマンドを積むフェーズ。バリアはRenderGraphが解決済みの状態で呼ばれる
		std::function<void(ID3D12GraphicsCommandList*, const ResourceRegistry&)> Execute;
	};

}
