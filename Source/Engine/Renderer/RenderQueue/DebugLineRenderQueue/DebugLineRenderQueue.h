#pragma once

// -------------------------------------------------------------------------------
// Includes
// -------------------------------------------------------------------------------
#include <Engine/Renderer/RendererItem/DebugLineDrawItem/DebugLineDrawItem.h>
#include <Engine/Mesh/DebugLineResource/DebugLineResource.h>

// -------------------------------------------------------------------------------
// DebugRenderQueue class
// 
// 概要 : 
//	DrawItemを蓄積し、まとめてコマンドリストへ発行する
//	submitはDX12APIを呼ばないためマルチスレッドから安全に呼べる
//	Executeは単一スレッドで、実際にコマンドリストへ記録する
// -------------------------------------------------------------------------------
class DebugLineRenderQueue
{
public:

	// -------------------------------------------------------------------------------
	// コンストラクタ
	// -------------------------------------------------------------------------------
	DebugLineRenderQueue();

	// -------------------------------------------------------------------------------
	// デストラクタ
	// -------------------------------------------------------------------------------
	~DebugLineRenderQueue();

	// -------------------------------------------------------------------------------
	// 初期化
	// -------------------------------------------------------------------------------
	bool Init(ID3D12Device* _pDevice, uint32_t _frameCount);

	// -------------------------------------------------------------------------------
	// 終了
	// -------------------------------------------------------------------------------
	void Term();

	// -------------------------------------------------------------------------------
	// @brief	DrawItemを積む
	// -------------------------------------------------------------------------------
	void Submit(const DebugLineDrawItem& _item);

	// -------------------------------------------------------------------------------
	// 1本のラインを積む
	// -------------------------------------------------------------------------------
	void SubmitLine(
		const Math::Vector3& _start,
		const Math::Vector3& _end,
		const Math::Vector4& _color);

	// -------------------------------------------------------------------------------
	// AABBを積む
	// -------------------------------------------------------------------------------
	void SubmitAABB(
		const Math::Vector3& _center,
		const Math::Vector3& _halfExtents,
		const Math::Vector4& _color);

	// -------------------------------------------------------------------------------
	// @brief	蓄積したDrawItemを順にコマンドリストへ発行する
	//			GameScene::OnRenderから呼ぶ
	// -------------------------------------------------------------------------------
	void Execute(ID3D12GraphicsCommandList* _pCmd, uint32_t _frameIndex);

	// -------------------------------------------------------------------------------
	// Item数取得
	// -------------------------------------------------------------------------------
	size_t GetItemCount() const;

	// -------------------------------------------------------------------------------
	// キューを破棄
	// -------------------------------------------------------------------------------
	void Clear();

private:

	// -------------------------------------------------------------------------------
	// private variables
	// -------------------------------------------------------------------------------

	static constexpr uint32_t		kMaxVertexCount = 65536;
	static constexpr uint32_t 		kMaxLineCount	= kMaxVertexCount / 2;
	std::vector<DebugLineDrawItem>	m_DrawItems;
	std::vector<DebugLineVertex>	m_Vertices;

	DebugLineResource m_LineResource;

	// constな参照処理でも排他制御するためmutable
	mutable std::mutex				m_Mutex;	// Submit()とExecute()の排他制御用

};
