#pragma once

// -------------------------------------------------------------------------------
// Includes
// -------------------------------------------------------------------------------

// 前方宣言
namespace RHI
{
	class Device;
}

// -------------------------------------------------------------------------------
// GraphicsView class
// 
// 概要 : 
//	Application / GameScene等の描画境界
//	DirectX12の型を公開せず、Pimplイディオムで実装を完全に隠蔽する
// -------------------------------------------------------------------------------
class GraphicsView
{
public:

	// -------------------------------------------------------------------------------
	// コンストラクタ
	// -------------------------------------------------------------------------------
	GraphicsView();

	// -------------------------------------------------------------------------------
	// デストラクタ
	// -------------------------------------------------------------------------------
	~GraphicsView();

	// -------------------------------------------------------------------------------
	// @brief	初期化
	// -------------------------------------------------------------------------------
	bool Init(void* _hWnd, uint32_t _width, uint32_t _height);
	
	// -------------------------------------------------------------------------------
	// @brief	終了
	// -------------------------------------------------------------------------------
	void Term();

	// -------------------------------------------------------------------------------
	// @brief	フレーム開始処理
	// @return	記録中のコマンドリスト。呼び出し側はvoid*型
	//			SceneManager等の既存APIに渡すだけで、中身を直接触らない
	// -------------------------------------------------------------------------------
	void* BeginFrame();

	// -------------------------------------------------------------------------------
	// @brief	フレーム終了処理
	// @param[in]	_pCmd	BeginFrame()で取得したコマンドリスト
	// -------------------------------------------------------------------------------
	void EndFrame(void* _pCmd);

	// -------------------------------------------------------------------------------
	// @brief	描画処理
	// -------------------------------------------------------------------------------
	void Present(uint32_t _syncInterval);

	// -------------------------------------------------------------------------------
	// @brief	GPUの完了待ち
	// -------------------------------------------------------------------------------
	void WaitForGPU();

	// -------------------------------------------------------------------------------
	// @brief	Sceneの切り替え時にFrameIndexを更新
	//			SceneManagerが切り替え直後に呼ぶ用途
	// -------------------------------------------------------------------------------
	void UpdateFrameIndexAfterSceneChange();

	// -------------------------------------------------------------------------------
	// @brief	FrameIndexの取得
	// -------------------------------------------------------------------------------
	uint32_t GetFrameIndex() const;

	// -------------------------------------------------------------------------------
	// @brief	デバイスを取得
	// -------------------------------------------------------------------------------
	RHI::Device* GetDevice();

private:

	// -------------------------------------------------------------------------------
	// @brief	内部実装（Impl）イディオム
	//			Engine層のみが使う
	//			Game層は使わない
	// -------------------------------------------------------------------------------
	class Impl;

	std::unique_ptr<Impl>	m_pImpl;

	GraphicsView	(const GraphicsView&) = delete;
	void operator = (const GraphicsView&) = delete;

};
