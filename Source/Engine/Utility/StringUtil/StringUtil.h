#pragma once

namespace StringUtil
{
	// -------------------------------------------------------------------------------
	// wchar_t → UTF-8変換
	// AssimpのReadFileはchar*(UTF-8)を要求するため
	// -------------------------------------------------------------------------------
	std::string ToUTF8(const std::wstring& _value);

	// -------------------------------------------------------------------------------
	// char*(UTF-8) → wstring変換
	// テクスチャパスをwstringで保持するために使う
	// -------------------------------------------------------------------------------
	std::wstring ToWString(const char* _value);

	// -------------------------------------------------------------------------------
	// std::string → wstring変換
	// テクスチャパスをwstringで保持するために使う
	// -------------------------------------------------------------------------------
	std::wstring ToWString(const std::string& _value);

	// -------------------------------------------------------------------------------
	// std::string_view(UTF-8) → wstring変換
	//
	// ToWStringと違い、終端のヌル文字に依存せず「見えている長さぶんだけ」を変換する
	// EditorUIのように部分文字列(string_view)を直接扱う層はこちらを使う
	// -------------------------------------------------------------------------------
	std::wstring Utf8ToWide(std::string_view _utf8);

	// -------------------------------------------------------------------------------
	// std::wstring_view → UTF-8変換
	//
	// Utf8ToWideの逆変換。EditorUIが編集結果をstd::stringへ書き戻すときに使う
	// -------------------------------------------------------------------------------
	std::string WideToUtf8(std::wstring_view _wide);
}
