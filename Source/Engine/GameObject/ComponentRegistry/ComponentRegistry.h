#pragma once
// -------------------------------------------------------------------------------
// Includes
// -------------------------------------------------------------------------------
class GameObject;
class Component;

// -------------------------------------------------------------------------------
// ComponentTypeInfo struct
//
// 概要 :
//	1種類のコンポーネントを「名前で」扱うために必要な手順をひとまとめにしたもの
//
//	GameObject::AddComponent<T>() はテンプレートのため、
//	「"MeshComponent" という名前のコンポーネントを付ける」ことが素直には書けない
//	そこで型ごとの手順を関数ポインタとして表に持ち、
//	呼ぶ側は表を引くだけでどの型でも同じように扱えるようにしている
//
//	これが必要になるのは
//		・ファイルから読み込む（型名しか残っていない）
//		・複製する（何を写せばよいか型ごとに違う）
//		・エディタのメニューから付け外しする
//	といった場面で、どれもエディタ専用ではない
//	そのためこの表はエンジン側に置いている
//
//	関数ポインタ（std::functionではなく）にしているのは、
//	この表が起動から終了まで変化しない静的なデータであることを型で示すため
// -------------------------------------------------------------------------------
struct ComponentTypeInfo
{
	// 保存や検索に使う内部名。GameObject側のクラス名と一致させる
	std::string_view TypeName;

	// 付いているかを調べる
	bool (*Has)(const GameObject& _object) = nullptr;

	// 付ける（すでに付いていれば既存のものを返す）
	Component* (*Add)(GameObject& _object) = nullptr;

	// 外す
	bool (*Remove)(GameObject& _object) = nullptr;

	// -------------------------------------------------------------------------------
	// 値の保存 / 復元
	//
	//	複製・プレファブ・シーンの保存・「コンポーネント削除の取り消し」は、
	//	どれも「今の値を写して、あとで戻す」という同じことをしている
	//	そこで経路をJSON1本にまとめ、すべてが必ず同じ結果になるようにしている
	//
	//	GPUリソースそのものは保存しない
	//	代わりに「どのモデルを使うか」という指定だけを保存し、
	//	実体の割り当てはシーンが行う（MeshComponentのコメントを参照）
	// -------------------------------------------------------------------------------
	void (*Save)(const GameObject& _object, nlohmann::json& _outJson) = nullptr;
	void (*Load)(GameObject& _object, const nlohmann::json& _json) = nullptr;
};

// -------------------------------------------------------------------------------
// ComponentRegistry
//
// 概要 :
//	名前で扱えるコンポーネントの一覧
//
//	新しいコンポーネントを対応させるときは、
//	ComponentRegistry.cpp の表へ1項目足すだけでよい
//	複製・プレファブ・シーンの保存が同時に対応する
//	（エディタでの見せ方だけは Editor::ComponentInspectors 側に足す）
// -------------------------------------------------------------------------------
namespace ComponentRegistry
{
	// @brief	登録されている全コンポーネント種別
	const std::vector<ComponentTypeInfo>& GetAll();

	// @brief	内部名から種別を引く。見つからなければnullptr
	const ComponentTypeInfo* Find(std::string_view _typeName);

	// -------------------------------------------------------------------------------
	// @brief	登録済みコンポーネントの中身を、まるごと別のオブジェクトへ写す
	//
	//	複製とプレファブの生成で使う
	//	登録されていないコンポーネントは写らない（写す手順が分からないため）
	// -------------------------------------------------------------------------------
	void CopyComponents(const GameObject& _source, GameObject& _destination);

	// -------------------------------------------------------------------------------
	// @brief	1つのコンポーネントの現在値を写し取る
	//
	//	コンポーネント削除の取り消しに使う
	//	付いていない場合は空のJSONを返す
	// -------------------------------------------------------------------------------
	nlohmann::json CaptureComponent(
		const GameObject&			_object,
		const ComponentTypeInfo&	_typeInfo);

	// -------------------------------------------------------------------------------
	// @brief	写し取った値からコンポーネントを復元する
	//
	//	付いていなければ追加してから値を戻す
	// -------------------------------------------------------------------------------
	void RestoreComponent(
		GameObject&					_object,
		const ComponentTypeInfo&	_typeInfo,
		const nlohmann::json&		_json);
}
