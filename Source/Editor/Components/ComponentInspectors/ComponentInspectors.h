#pragma once
// -------------------------------------------------------------------------------
// Includes
// -------------------------------------------------------------------------------
class GameObject;

namespace Editor
{
	struct EditorContext;

	// -------------------------------------------------------------------------------
	// ComponentDisplayInfo struct
	//
	// 概要 :
	//	1種類のコンポーネントを「エディタでどう見せるか」の情報
	//
	//	何ができる型なのか（追加・削除・保存の手順）はエンジン側の
	//	ComponentRegistry が持っている
	//	こちらが持つのは表示名や見せ方といった、エディタにしか関係しない部分だけ
	//
	//	2つに分けている理由 :
	//		プレファブやシーンの読み込みは、エディタが無い状態でも動く必要がある
	//		そのため型の扱い方はエンジンに置き、
	//		「日本語の表示名」「削除ボタンを出すか」「どう描くか」はここに残した
	//
	//	登録は型名で結び付ける
	//	見せ方が登録されていない型でも、型名をそのまま表示して扱える
	// -------------------------------------------------------------------------------
	struct ComponentDisplayInfo
	{
		std::string_view TypeName;		// ComponentRegistryの内部名と一致させる
		std::string_view DisplayName;	// 画面に出す名前

		// -------------------------------------------------------------------------------
		// 取り外せるか
		//
		//	Transformは「シーン上のどこにあるか」を表す最低限の情報で、
		//	描画コンポーネントもこれを前提にしているため外させない
		// -------------------------------------------------------------------------------
		bool IsRemovable = true;

		// 中身の描き方。nullptrなら中身を持たない（見出しだけ出す）
		void (*Draw)(EditorContext& _ctx, GameObject& _object) = nullptr;
	};

	// -------------------------------------------------------------------------------
	// ComponentInspectors
	//
	// 概要 :
	//	コンポーネントの「見せ方」を集めたもの
	//
	//	インスペクタのパネルは、見出し・折りたたみ・削除ボタンといった
	//	どの型でも同じ部分だけを描き、中身はここへ任せる
	//	そのため、新しいコンポーネントを足してもパネル側は変更しなくてよい
	//
	// 責務の分担 :
	//	ComponentRegistry	どんな型があり、追加・削除・保存をどうするか（エンジン）
	//	ComponentInspectors	その型を画面にどう出すか（このファイル）
	//	InspectorPanel		どの順で並べ、どこに削除ボタンを置くか
	//
	// 値を書き換えたときは ObjectCommands / ComponentCommands 経由で履歴へ積む
	// 直接コンポーネントを書き換えると、その操作だけUndoできなくなるため
	// -------------------------------------------------------------------------------
	namespace ComponentInspectors
	{
		// -------------------------------------------------------------------------------
		// @brief	型名に対応する見せ方を返す
		//
		//	登録が無い型には、型名をそのまま表示名にした既定の情報を返す
		//	（エンジン側に型を足して、こちらへの登録を忘れても表示は壊れない）
		// -------------------------------------------------------------------------------
		const ComponentDisplayInfo& GetDisplay(std::string_view _typeName);

		// -------------------------------------------------------------------------------
		// 型ごとの中身
		//
		//	どれも ComponentDisplayInfo の表から呼ばれる
		//	表に載せるため、シグネチャは全種類でそろえてある
		// -------------------------------------------------------------------------------

		// @brief	Transformの中身（位置・回転・大きさ）
		//			ドラッグ中は毎フレーム値が変わるため、履歴へ積むのは指を離した時点
		void DrawTransform(EditorContext& _ctx, GameObject& _object);

		// @brief	Meshの中身（描くモデルの選択と表示切り替え）
		void DrawMesh(EditorContext& _ctx, GameObject& _object);

		// @brief	Meshletの中身（描くモデルの選択と表示切り替え）
		void DrawMeshlet(EditorContext& _ctx, GameObject& _object);

		// @brief	BoxCollisionの中身（当たり判定のサイズ、デバッグラインの表示非表示）
		void DrawBoxCollision(EditorContext& _ctx, GameObject& _object);
	}
}
