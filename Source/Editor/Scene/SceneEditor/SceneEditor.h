#pragma once
// -------------------------------------------------------------------------------
// Includes
// -------------------------------------------------------------------------------
#include <Editor/EditorContext.h>

namespace Editor
{
	// -------------------------------------------------------------------------------
	// SceneEditor
	//
	// 概要 :
	//	シーンの保存と読み込みを、エディタの操作として扱うための層
	//
	//	シーンの形と読み書きはエンジン側(SceneIO)にある
	//	ここが受け持つのは、エディタにしか関係しない次の3つ
	//		・コンテンツフォルダのどこへ保存するか（AssetDatabase経由）
	//		・読み込んだあとに選択と履歴をどうするか
	//		・いまどのシーンファイルを開いているかを覚えておくこと
	//
	//	プレファブに対する PrefabSystem と、まったく同じ立ち位置にある
	//
	// 履歴について :
	//	シーンを開くとオブジェクトがすべて作り直されるため、
	//	それ以前の履歴は指す先を失う
	//	そのため読み込みの直後に履歴を捨てる
	//	（「シーンを開いたことをUndoで取り消す」ことはできない）
	// -------------------------------------------------------------------------------
	namespace SceneEditor
	{
		// -------------------------------------------------------------------------------
		// @brief	今のシーンを、コンテンツフォルダへ新しいファイルとして保存する
		//
		//	保存先はコンテンツブラウザで今開いているフォルダ
		//	同名のファイルがある場合は連番が付く
		//
		// @param[in]	_name		付けたいシーン名（拡張子は不要）
		// @param[out]	_outPath	実際に作られたファイルのパス
		// @return	true : 保存できた
		// -------------------------------------------------------------------------------
		bool SaveAs(
			EditorContext&			_ctx,
			std::string_view		_name,
			std::filesystem::path&	_outPath);

		// -------------------------------------------------------------------------------
		// @brief	今開いているシーンファイルへ上書き保存する
		//
		//	まだ一度も保存していない場合は何もしない（保存先が決まらないため）
		//
		// @return	true : 保存できた
		// -------------------------------------------------------------------------------
		bool Save(EditorContext& _ctx);

		// -------------------------------------------------------------------------------
		// @brief	シーンファイルを読み込み、今のシーンの中身を置き換える
		//
		//	今あるオブジェクトはすべて消える
		//
		// @return	true : 読み込めた
		// -------------------------------------------------------------------------------
		bool Open(EditorContext& _ctx, const std::filesystem::path& _path);

		// -------------------------------------------------------------------------------
		// @brief	シーンを空にする（新規作成）
		//
		//	保存先の記憶も消えるため、次の保存は「名前を付けて保存」になる
		// -------------------------------------------------------------------------------
		void CreateNew(EditorContext& _ctx);

		// -------------------------------------------------------------------------------
		// いま開いているシーン
		//
		//	一度も保存・読み込みをしていない場合は空
		//	メニューの表示と、上書き保存ができるかの判定に使う
		// -------------------------------------------------------------------------------
		const std::filesystem::path& GetCurrentPath();
		std::string GetCurrentName();
		bool HasCurrentPath();
	}
}
