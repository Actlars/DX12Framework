#pragma once
// -------------------------------------------------------------------------------
// Includes
// -------------------------------------------------------------------------------
#include <Editor/Commands/IEditorCommand.h>

namespace Editor
{
	// -------------------------------------------------------------------------------
	// CommandHistory class
	//
	// 概要 :
	//	実行した操作を並べて覚えておき、行き来できるようにする（Undo / Redo）
	//
	//	仕組みは2つの山（スタック）だけ
	//		実行		… 操作を行い「戻せる山」へ積む。「やり直せる山」は捨てる
	//		元に戻す	… 戻せる山から1つ取り出してUndoし、やり直せる山へ移す
	//		やり直す	… やり直せる山から1つ取り出してExecuteし、戻せる山へ戻す
	//
	//	新しい操作を行った時点で「やり直せる山」を捨てるのは、
	//	そこから先の未来が分岐して、もう再現できなくなるため
	//
	// 履歴を捨てるときの決まり :
	//	削除されたGameObjectの実体はコマンドが預かっている（GameObjectFactory参照）
	//	そのため「捨てる範囲」を間違えると、まだ生きているつもりの実体が消える
	//	このクラスは必ず時系列の端からまとめて捨てる
	//		・やり直せる山	… 新しい操作を実行した時点で、そこから先をすべて
	//		・戻せる山		… 上限を超えたぶんを、いちばん古い方から
	//	どちらも「ある時点から後ろ全部」または「前全部」のため、
	//	実体を預かるコマンドだけが消えて、それを指すコマンドが残ることはない
	//
	//	所有者はEditorApp
	//	シーンが切り替わったときは、前のシーンのオブジェクトを指したままにしないよう
	//	必ずClear()を呼ぶ
	// -------------------------------------------------------------------------------
	class CommandHistory
	{
	public:

		// -------------------------------------------------------------------------------
		// @brief	操作を実行し、履歴へ積む
		//
		//	Executeがfalseを返した操作（対象が見つからない等）は積まない
		//	戻す必要のないものを履歴に残すと、Undoしても何も起きない項目が増えるため
		//
		// @param[in]	_ctx		共有参照
		// @param[in]	_pCommand	実行する操作
		// @return	true : 実行して履歴へ積んだ
		// -------------------------------------------------------------------------------
		bool Execute(EditorContext& _ctx, std::unique_ptr<IEditorCommand> _pCommand);

		// @brief	直前の操作を取り消す
		bool Undo(EditorContext& _ctx);

		// @brief	取り消した操作をやり直す
		bool Redo(EditorContext& _ctx);

		bool CanUndo() const { return !m_UndoStack.empty(); }
		bool CanRedo() const { return !m_RedoStack.empty(); }

		// -------------------------------------------------------------------------------
		// 次に戻る / 進む操作の名前
		//
		//	メニューに「元に戻す : 名前の変更」と出すために使う
		//	何もない場合は空を返す
		// -------------------------------------------------------------------------------
		std::string_view GetUndoLabel() const;
		std::string_view GetRedoLabel() const;

		// -------------------------------------------------------------------------------
		// @brief	履歴をすべて捨てる
		//
		//	シーンの切り替え時に必ず呼ぶ
		//	コマンドは前のシーンのGameObjectを指しているため、
		//	残したままだと別のシーンへ復元してしまう
		// -------------------------------------------------------------------------------
		void Clear();

		size_t GetUndoCount() const { return m_UndoStack.size(); }
		size_t GetRedoCount() const { return m_RedoStack.size(); }

	private:

		// -------------------------------------------------------------------------------
		// 覚えておく操作の数の上限
		//
		//	削除されたオブジェクトの実体も履歴が抱えるため、
		//	無制限にすると使うほどメモリが増え続ける
		//	上限を超えたぶんは、いちばん古い操作から捨てる
		// -------------------------------------------------------------------------------
		static constexpr size_t kMaxHistory = 100;

		// 先頭が最古、末尾が最新。末尾から取り出して使う
		std::vector<std::unique_ptr<IEditorCommand>> m_UndoStack;
		std::vector<std::unique_ptr<IEditorCommand>> m_RedoStack;
	};
}
