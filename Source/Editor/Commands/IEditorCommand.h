#pragma once

namespace Editor
{
	struct EditorContext;

	// -------------------------------------------------------------------------------
	// IEditorCommand class
	//
	// 概要 :
	//	「取り消せる操作」1つ分を表すインターフェース
	//
	//	エディタからシーンを書き換える操作は、すべてこの形にしてから実行する
	//	書き換え方と戻し方が必ず同じクラスの中に並ぶため、
	//	「戻す処理だけ実装し忘れる」ということが起きにくい
	//
	//	Execute は「最初の実行」と「やり直し(Redo)」の両方で呼ばれる
	//	そのため、何度呼んでも同じ結果になるように書く必要がある
	//	（例 : 生成した実体を覚えておき、2回目以降はそれを使い回す）
	//
	// 使い方 :
	//	class MyCommand : public IEditorCommand { ... };
	//	_ctx.pHistory->Execute(_ctx, std::make_unique<MyCommand>(...));
	//
	// 寿命についての約束 :
	//	コマンドがGameObjectを生ポインタで持つ場合、
	//	そのオブジェクトは「シーンの中」か「別のコマンドの中」のどちらかに必ず居る
	//	履歴を捨てるときは、時系列で後ろにあるコマンドから先にまとめて捨てるため、
	//	実体を預かっているコマンドより先に、それを参照するコマンドが消えることはない
	// -------------------------------------------------------------------------------
	class IEditorCommand
	{
	public:

		virtual ~IEditorCommand() = default;

		// -------------------------------------------------------------------------------
		// @brief	操作を行う（最初の実行 / やり直し）
		//
		// @return	true : 実行できた
		//			false : 対象が見つからないなど、実行できなかった
		//					falseを返した操作は履歴に積まれない
		// -------------------------------------------------------------------------------
		virtual bool Execute(EditorContext& _ctx) = 0;

		// @brief	操作を取り消し、実行前の状態へ戻す
		virtual void Undo(EditorContext& _ctx) = 0;

		// -------------------------------------------------------------------------------
		// @brief	メニューに出す操作名
		//
		//	「元に戻す : オブジェクトの作成」のように表示するために使う
		//	何が戻るのかが分かるよう、操作の内容が伝わる名前にする
		// -------------------------------------------------------------------------------
		virtual std::string_view GetLabel() const = 0;
	};
}
