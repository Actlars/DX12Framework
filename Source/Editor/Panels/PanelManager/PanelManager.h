#pragma once
// -------------------------------------------------------------------------------
// Includes
// -------------------------------------------------------------------------------
#include <Editor/Panels/IEditorPanel.h>

namespace Editor
{
	// -------------------------------------------------------------------------------
	// PanelManager class
	//
	// 概要 :
	//	エディタのパネル一覧を所有し、毎フレームまとめて描くクラス
	//
	//	担当すること
	//		- ウィンドウのBegin / End とタイトル・初期配置の適用
	//		- 閉じられたパネルの後片付け（EditorUI側のウィンドウ破棄も含む）
	//		- 実行中に増える動的パネル（エフェクトエディタ等）の受け入れ
	//
	//	担当しないこと
	//		- パネルの中身。それは各パネル自身のOnGUIが持つ
	//
	//	描画中に新しいパネルが追加されても安全なよう、追加は一度保留してから反映する
	// -------------------------------------------------------------------------------
	class PanelManager
	{
	public:

		// -------------------------------------------------------------------------------
		// @brief	パネルを登録する
		//
		//	描画の途中で呼ばれた場合は保留され、そのフレームの終わりに反映される
		//
		// @return	登録された（または保留中の）パネルへのポインタ。所有権はManagerが持つ
		// -------------------------------------------------------------------------------
		IEditorPanel* Add(std::unique_ptr<IEditorPanel> _panel);

		// -------------------------------------------------------------------------------
		// @brief	すべてのパネルを描く
		//
		// @param[in]	_ctx	各パネルへ渡す共有参照
		// -------------------------------------------------------------------------------
		void DrawAll(EditorContext& _ctx);

		// -------------------------------------------------------------------------------
		// @brief	自前のGPU描画を持つパネルに、描画の機会を与える
		//
		//	DrawAllのあと、バックバッファへ描く前に呼ぶ
		//	表示されていないパネルは呼ばない
		// -------------------------------------------------------------------------------
		void RenderAll(EditorContext& _ctx, ID3D12GraphicsCommandList* _pCmd);

		// -------------------------------------------------------------------------------
		// @brief	指定した種類のパネルが何枚開かれているかを数える
		//
		//	同じウィンドウを増やしすぎないよう、上限の判定に使う
		//	描画中に追加された保留中のパネルも数に含める
		// -------------------------------------------------------------------------------
		int CountOfType(std::string_view _typeName) const;

		// -------------------------------------------------------------------------------
		// @brief	タイトルが一致するパネルを探す
		//
		//	同じアセットのエディタを二重に開かないための確認に使う
		// -------------------------------------------------------------------------------
		IEditorPanel* Find(std::string_view _title);

		// -------------------------------------------------------------------------------
		// @brief	指定した型の最初のパネルを返す
		//
		//	メニューから「ヒエラルキーを表示」のように、常設パネルを開き直すのに使う
		// -------------------------------------------------------------------------------
		template<typename T>
		T* Get()
		{
			for (const auto& panel : m_Panels)
			{
				if (T* pTyped = dynamic_cast<T*>(panel.get()))
				{
					return pTyped;
				}
			}
			return nullptr;
		}

		// -------------------------------------------------------------------------------
		// @brief	タイトルを指定してパネルを表示状態にする
		//
		// @return	見つかった場合はtrue
		// -------------------------------------------------------------------------------
		bool Open(std::string_view _title);

		// 常設パネルをメニューへ並べるための一覧
		const std::vector<std::unique_ptr<IEditorPanel>>& GetPanels() const { return m_Panels; }

	private:

		// 閉じられた一時パネルを破棄し、EditorUI側のウィンドウも消す
		void RemoveClosedPanels(EditorContext& _ctx);

		std::vector<std::unique_ptr<IEditorPanel>> m_Panels;

		// DrawAllの最中に追加されたパネル。反復中のvector書き換えを避けるための待ち行列
		std::vector<std::unique_ptr<IEditorPanel>> m_PendingPanels;

		bool m_Drawing = false;
	};
}
