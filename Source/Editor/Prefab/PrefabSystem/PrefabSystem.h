#pragma once
// -------------------------------------------------------------------------------
// Includes
// -------------------------------------------------------------------------------
#include <Editor/EditorContext.h>
#include <Editor/Prefab/PrefabAsset/PrefabAsset.h>

class GameObject;

namespace Editor
{
	// -------------------------------------------------------------------------------
	// PrefabSystem
	//
	// 概要 :
	//	プレファブ（オブジェクトの設計図）と、シーン上の実体をつなぐ処理
	//
	//	なぜ必要か :
	//		同じ構成のオブジェクトを何度も手で組み立てるのは手間で、間違いも起きる
	//		1体を組み立てたら設計図として保存し、以後はそれを置くだけにできる
	//		設計図はコンテンツフォルダのファイルなので、
	//		エディタを閉じても、別のシーンでも使い回せる
	//
	//	いまの範囲 :
	//		保存できるのは ComponentRegistry に登録済みのコンポーネントの値まで
	//		「置いたあとに設計図を直すと、置いてあるものにも反映される」という
	//		UE5のプレファブのような連動は持たない（置いた時点で切り離される）
	//
	// 責務の分担 :
	//	PrefabAsset			設計図そのものと、テキストとの相互変換
	//	ComponentRegistry	コンポーネント1つぶんの値の写し取り
	//	PrefabSystem		GameObjectとの変換、ファイルの保存と読み込み（このファイル）
	//	AssetDatabase		実際のファイル作成
	// -------------------------------------------------------------------------------
	namespace PrefabSystem
	{
		// プレファブファイルの拡張子。判定と保存の両方でここを参照する
		constexpr std::string_view kExtension = ".prefab";

		// -------------------------------------------------------------------------------
		// @brief	シーン上のオブジェクトから設計図を作る
		//
		// @param[in]	_object	写し取る対象
		// -------------------------------------------------------------------------------
		PrefabAsset CaptureFromObject(const GameObject& _object);

		// -------------------------------------------------------------------------------
		// @brief	設計図からオブジェクトを組み立てる（シーンにはまだ入れない）
		//
		//	知らない型のコンポーネントは読み飛ばす
		//	古いプレファブや、まだ登録していない型が入っていても開けるようにするため
		//
		// @param[in]	_ctx		共有参照（重複しない名前を決めるのに使う）
		// @param[in]	_prefab		もとにする設計図
		// @return	組み立てたオブジェクト（所有権つき）
		// -------------------------------------------------------------------------------
		std::unique_ptr<GameObject> Build(const EditorContext& _ctx, const PrefabAsset& _prefab);

		// -------------------------------------------------------------------------------
		// @brief	オブジェクトをプレファブとしてコンテンツフォルダへ保存する
		//
		//	保存先はコンテンツブラウザで今開いているフォルダ
		//	同名のファイルがある場合は連番が付く
		//
		// @param[in]	_object		保存する対象
		// @param[out]	_outPath	実際に作られたファイルのパス
		// @return	true : 保存できた
		// -------------------------------------------------------------------------------
		bool SaveToContent(
			EditorContext&			_ctx,
			const GameObject&		_object,
			std::filesystem::path&	_outPath);

		// -------------------------------------------------------------------------------
		// @brief	プレファブファイルを読み込む
		//
		// @return	true : 読み込めた
		// -------------------------------------------------------------------------------
		bool LoadFromFile(const std::filesystem::path& _path, PrefabAsset& _outPrefab);

		// -------------------------------------------------------------------------------
		// @brief	プレファブファイルを読み、シーンへ1体置く
		//
		//	配置は取り消し可能な操作として履歴へ積まれる
		//
		// @return	置いたオブジェクト。失敗した場合はnullptr
		// -------------------------------------------------------------------------------
		GameObject* InstantiateFromFile(EditorContext& _ctx, const std::filesystem::path& _path);

		// @brief	そのパスがプレファブファイルかどうか
		bool IsPrefabPath(const std::filesystem::path& _path);
	}
}
