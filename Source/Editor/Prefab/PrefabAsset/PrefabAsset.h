#pragma once

namespace Editor
{
	// -------------------------------------------------------------------------------
	// PrefabComponentData struct
	//
	// 概要 :
	//	プレファブに記録された、コンポーネント1つぶんの情報
	//
	//	型そのものではなく「型の名前」と「値」で持つ
	//	ファイルはC++の型を知らないため、名前で引き当てるしかないのと、
	//	知らない型が入っていても読み飛ばせるようにするため
	// -------------------------------------------------------------------------------
	struct PrefabComponentData
	{
		std::string		TypeName;	// ComponentRegistryの内部名（"TransformComponent"など）
		nlohmann::json	Values;		// その型ごとの値
	};

	// -------------------------------------------------------------------------------
	// PrefabAsset struct
	//
	// 概要 :
	//	「オブジェクト1体分の設計図」
	//
	//	シーンに置かれた実体ではなく、そこから写し取った値だけを持つ
	//	同じ設計図から何体でも作れ、ファイルとして保存して使い回せる
	//
	//	GameObjectそのものを保存しない理由 :
	//		GameObjectはGPUリソースへのポインタなど、実行中にしか意味を持たない
	//		ものを抱えている。値だけを抜き出しておくことで、
	//		起動をまたいでも、別のシーンでも同じように復元できる
	//
	//	この構造体はUIもファイルI/Oも知らない、ただの入れ物
	//		読み書き			SerializePrefab / DeserializePrefab（このファイル）
	//		GameObjectとの変換	PrefabSystem
	// -------------------------------------------------------------------------------
	struct PrefabAsset
	{
		std::string	Name	= "New Prefab";	// 配置したときのオブジェクト名の元になる
		bool		Active	= true;

		// 記録順に並ぶ。復元もこの順で行う
		std::vector<PrefabComponentData> Components;
	};

	// -------------------------------------------------------------------------------
	// @brief	プレファブをテキスト(JSON)へ書き出す
	//
	//	人が読める形にしておくことで、差分が追え、手で直すこともできる
	// -------------------------------------------------------------------------------
	std::string SerializePrefab(const PrefabAsset& _prefab);

	// -------------------------------------------------------------------------------
	// @brief	テキスト(JSON)からプレファブを読み込む
	//
	//	見つかったキーだけを反映する方針にしているため、
	//	項目が増えても古いファイルはそのまま開ける
	//
	// @return	true : 読み込めた / false : JSONとして壊れている
	// -------------------------------------------------------------------------------
	bool DeserializePrefab(std::string_view _json, PrefabAsset& _outPrefab);
}
